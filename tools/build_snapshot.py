"""Bundle data/*.json into assets/js/data-snapshot.js so the site also works when index.html is opened
directly from disk (file://), where browsers block fetch(). When hosted, the live JSON files always win.
Run after editing data:  python3 tools/build_snapshot.py   (Python 3.8+, no packages needed)"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
snap = {p.stem: json.loads(p.read_text(encoding='utf-8')) for p in sorted((root / 'data').glob('*.json'))}
out = root / 'assets' / 'js' / 'data-snapshot.js'
out.write_text('/* AUTO-GENERATED by tools/build_snapshot.py from data/*.json. Do not edit by hand. */\nwindow.RFT_SNAPSHOT=' + json.dumps(snap, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
print('wrote', out.relative_to(root), 'with', ', '.join(snap))
